import os
from django.conf import settings
from google import genai
from google.genai import types

def get_gemini_client():
    """Ініціалізує та повертає клієнта Gemini API за допомогою API-ключа"""
    api_key = os.environ.get('GEMINI_API_KEY') or getattr(settings, 'GEMINI_API_KEY', None)
    if not api_key:
        raise ValueError("GEMINI_API_KEY не знайдено в змінних середовища чи налаштуваннях Django.")
    return genai.Client(api_key=api_key)

def generate_initial_assessment(gender, diagnosis, clinical_state_notes, total_fractions, dose_per_fraction, irradiation_zone, today_date_str):
    """
    Генерує первинний огляд для пацієнта без персональних даних.
    """
    client = get_gemini_client()
    
    gender_text = "чоловіча" if gender == 'M' else "жіноча"
    
    try:
        total_dose = float(total_fractions) * float(dose_per_fraction)
        total_dose_str = f"{total_dose:.1f}"
    except (ValueError, TypeError):
        total_dose_str = "___"
        
    prompt = f"""
    Згенеруй медичний документ "Первинний огляд лікаря з радіаційної онкології" на основі наступних знеособлених даних:
    - Стать пацієнта: {gender_text}
    - Встановлений діагноз: {diagnosis}
    - Клінічні нотатки лікаря про стан пацієнта: {clinical_state_notes or 'загальний стан задовільний, активних скарг немає.'}
    - Зона опромінення: {irradiation_zone or 'не вказано'}
    - Запланована кількість фракцій: {total_fractions or 'не вказано'}
    - Разова вогнищева доза (РВД): {dose_per_fraction or 'не вказано'} Гр
    - Дата огляду: {today_date_str}
    
    Вимоги до документу:
    1. Мова документу: українська.
    2. Зверху документа виведіть заголовок та дату огляду строго за таким зразком:
       **Первинний огляд лікаря з радіаційної онкології**
       
       **Дата огляду:** {today_date_str}
       
       Категорично заборонено виводити будь-які демографічні рядки на початку (наприклад, "Пацієнтка: жіночої статі" або "Стать: ..."). Згадуйте пацієнта виключно нейтрально в тексті огляду ("Пацієнт...", "Пацієнтка...").
       
    3. Документ має бути структурованим за такими розділами:
       - **Скарги**: опис скарг відповідно до діагнозу та нотаток стану.
       - **Анамнез хвороби (Anamnesis morbi)**: логічна історія виникнення та розвитку хвороби на основі діагнозу.
       - **Анамнез життя (Anamnesis vitae)**: загальні відомості.
       - **Об'єктивний стан та локальний статус (Status localis)**: У цьому розділі першим рядком обов'язково має бути вказано оцінку статусу активності за шкалою ECOG (наприклад: "Статус активності за ECOG: 1"), яку ви повинні знайти та витягнути з переданих клінічних нотаток лікаря (якщо оцінки ECOG немає в нотатках, виведіть "Статус активності за ECOG: 0" або на основі опису скарг). Далі опишіть загальний опис стану пацієнта: загальний стан, системи дихання, серцево-судинна система (пульс, АТ в межах норми відповідно до скарг), опис стану тканин та вогнища у зоні {irradiation_zone or 'проекції пухлини'} відповідно до діагнозу.
       - **Обґрунтування діагнозу та план лікування**: Цей розділ має містити ЛИШЕ наступне твердження, сформоване строго за шаблоном:
         "Планується [післяопераційний/радикальний] курс дистанційної променевої терапії на {irradiation_zone or 'ложе пухлини'} РВД - {dose_per_fraction or '___'} Гр, СВД - {total_dose_str} Гр. Проведено КТ-симуляцію, планування. Розпочато лікування."
         (Замість [післяопераційний/радикальний] обери найбільш підходящий за клінічним змістом варіант).
         
    4. ЖОДНИХ імен, прізвищ чи дат народження пацієнта (навіть у вигляді порожніх ліній чи заглушок).
    5. Не вигадуй жодних додаткових доз або зон лікування, крім тих, що передані у параметрах.
    """
    
    response = client.models.generate_content(
        model='gemini-2.5-flash',
        contents=prompt,
        config=types.GenerateContentConfig(
            system_instruction="Ти досвідчений лікар з радіаційної онкології (радіаційний онколог). Пиши виключно професійною українською медичною термінологією."
        )
    )
    return response.text

def generate_diary_entry(gender, diagnosis, fraction_number, ecog_status, ctcae_grade, clinical_state_notes, diary_type):
    """
    Генерує щоденниковий запис про стан пацієнта для конкретного сеансу лікування.
    """
    client = get_gemini_client()
    
    gender_text = "чоловіча" if gender == 'M' else "жіноча"
    
    ecog_descriptions = {
        0: "0 (активний, без обмежень)",
        1: "1 (обмеження значного фізичного навантаження)",
        2: "2 (здатний до самообслуговування, не може працювати)",
        3: "3 (обмежене самообслуговування, більше 50% часу в ліжку/кріслі)",
        4: "4 (повна інвалідність)"
    }
    
    if diary_type == 'admission':
        diary_type_instruction = (
            "ввідний щоденник (При поступленні). Обов'язково вкажи у тексті, "
            "що пацієнт розпочав заплановане лікування та пройшов першу фракцію променевої терапії."
        )
    elif diary_type == 'discharge':
        diary_type_instruction = (
            "виписний щоденник (Завершення лікування). Обов'язково вкажи у тексті, "
            "що пацієнт успішно закінчив запланований курс променевої терапії, "
            "та надай можливі короткі рекомендації щодо подальшого догляду/контролю."
        )
    else:
        diary_type_instruction = (
            "щотижневий щоденник (перебіг лікування). Опиши поточний динамічний стан пацієнта "
            "у процесі проходження терапії (переносимість лікування, реакції)."
        )
        
    prompt = f"""
    Згенеруй щоденниковий запис про стан пацієнта під час променевої терапії на основі наступних знеособлених даних:
    - Стать: {gender_text}
    - Діагноз: {diagnosis}
    - Номер сеансу (фракції): {fraction_number or 'поточний сеанс'}
    - Статус активності за шкалою ECOG: {ecog_descriptions.get(ecog_status, str(ecog_status))}
    - Ступінь токсичності за CTCAE v5.0: {ctcae_grade} (оцінка променевих реакцій)
    - Нотатки лікаря про поточні симптоми: {clinical_state_notes or 'скарг немає, переносить опромінення задовільно.'}
    
    Тип щоденника, який необхідно згенерувати: {diary_type_instruction}
    
    Вимоги до документу:
    1. Мова документу: українська.
    2. Format щоденника: короткий, професійний, клінічний запис.
    3. Структура щоденника має містити:
       - **Загальний стан**: оцінка загального самопочуття, пульс, АТ, статус ECOG.
       - **Скарги**: опис скарг відповідно до нотаток та діагнозу.
       - **Локальний статус / променеві реакції**: опис стану тканин у зоні опромінення з урахуванням ступеня токсичності за CTCAE v5.0 {ctcae_grade} (наприклад, для Grade 0-1: прояви реакцій відсутні або мінімальна еритема; для Grade 2: помірна еритема, сухе лущення; для Grade 3: вологе лущення тощо).
       - **Висновок**: рішення щодо продовження променевої терапії у запланованому режимі (або про завершення лікування, якщо це виписний щоденник).
    4. ЖОДНИХ імен, прізвищ чи персональних ідентифікаторів пацієнта. Не використовуй заглушки.
    """
    
    response = client.models.generate_content(
        model='gemini-2.5-flash',
        contents=prompt,
        config=types.GenerateContentConfig(
            system_instruction="Ти лікар з радіаційної онкології (радіаційний онколог), що веде щоденники лікування. Пиши лаконічно, використовуючи загальноприйнятий медичний жаргон українських стаціонарів."
        )
    )
    return response.text

def generate_discharge_summary(gender, diagnosis, total_fractions, dose_per_fraction, received_dose, clinical_state_notes):
    """
    Генерує виписний епікриз / виписні дані для пацієнта на основі завершеного курсу.
    """
    client = get_gemini_client()
    
    gender_text = "чоловіча" if gender == 'M' else "жіноча"
    
    prompt = f"""
    Згенеруй виписні дані (епікриз виписки зі стаціонару) після проведення курсу променевої терапії на основі наступних знеособлених даних:
    - Стать: {gender_text}
    - Діагноз: {diagnosis}
    - Проведено фракцій: {total_fractions or 'не вказано'}
    - Разова доза (РВД): {dose_per_fraction or 'не вказано'} Гр
    - Сумарна отримана доза (СОД): {received_dose or 'не вказано'} Гр
    - Опис стану та рекомендації при виписці: {clinical_state_notes or 'рекомендовано спостереження онколога.'}
    
    Вимоги до документу:
    1. Мова: українська.
    2. Структура документу має містити:
       - **Діагноз при виписці**: структуроване представлення діагнозу.
       - **Проведене лікування**: чітко зафіксувати курс дистанційної променевої терапії, вказавши РВД {dose_per_fraction or '___'} Гр, СОД {received_dose or '___'} Гр та кількість виконаних фракцій {total_fractions or '___'}.
       - **Стан пацієнта при виписці**: оцінка загального самопочуття, переносимості лікування на основі нотаток стану.
       - **Рекомендації**: рекомендації щодо догляду за шкірою/слизовими після променевої терапії, симптоматичне лікування, терміни контрольних оглядів та аналізів крові.
    3. ЖОДНИХ імен, прізвищ чи дат народження пацієнта. Не використовуй заглушки.
    """
    
    response = client.models.generate_content(
        model='gemini-2.5-flash',
        contents=prompt,
        config=types.GenerateContentConfig(
            system_instruction="Ти завідувач радіологічного відділення, що формує виписку пацієнта. Пиши професійно, структуровано, з чіткими рекомендаціями українською мовою."
        )
    )
    return response.text
